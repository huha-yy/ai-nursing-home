# chat 英文回答的术语指令分组（_enum_terms_clause 从 ENUM_ZH_EN 生成词表，
# 单一事实源——两处不会漂移）。工单类型 24 条太长不进 prompt。
ENUM_TERM_GROUPS: dict[str, tuple[str, ...]] = {
    "care levels": ("自理", "半护", "全护", "失智"),
    "meal types": ("早餐", "午餐", "晚餐"),
    "gender": ("男", "女"),
    "incident categories": ("摔倒", "突发不适", "情绪异常"),
    "shifts": ("白班", "夜班"),
}


def enum_display(value, lang: str):
    """渲染前把中文枚举值换英文：lang=en 且整值命中 ENUM_ZH_EN 才替换，
    其余（zh / 未知值 / 非 str）原样返回。整值匹配——不做子串替换。"""
    if lang == "en" and isinstance(value, str):
        return ENUM_ZH_EN.get(value, value)
    return value


def enum_terms_clause() -> str:
    """en 版 chat prompt 的枚举术语翻译指令（从 ENUM_ZH_EN 生成）。"""
    groups = "; ".join(
        f"{label} ({'/'.join(keys)} → {'/'.join(ENUM_ZH_EN[k] for k in keys)})"
        for label, keys in ENUM_TERM_GROUPS.items()
    )
    return (
        f"When the data mentions Chinese enum terms — {groups} — render them "
        "in English; keep person names, dish names and place names in Chinese "
        "as-is."
    )


def normalize_lang(raw: str | None) -> str:
    """Map a raw cookie value to a supported language code.

    Unknown / missing / malformed → DEFAULT_LANG. Never raises.
    """
    if raw in LANGS:
        return raw  # type: ignore[return-value]
    return DEFAULT_LANG


def translate(lang: str, key: str) -> str:
    """Look up a message. Missing key → returns the key itself (dev-visible)."""
    lang = normalize_lang(lang)
    return MESSAGES[lang].get(key, key)


def translator(lang: str) -> Callable[[str], str]:
    """Return a `t(key)` bound to a (normalized) language code. Pure."""
    lang = normalize_lang(lang)
    return lambda key: translate(lang, key)


def dump_prefixed(lang: str, prefixes: tuple[str, ...]) -> str:
    """Serialize all messages under the given key prefixes to a JSON string.

    For inline <script> i18n: the route passes the result as the `i18n_page`
    context var, the template does `var I18N = JSON.parse(...)` and reads
    `I18N["<key minus prefix>"]`. Prefix is stripped so JS keys stay short.
    Starlette Jinja2 has no |tojson-for-JS-string story, hence this helper.
    """
    lang = normalize_lang(lang)
    msgs = MESSAGES[lang]
    out: dict[str, str] = {}
    for prefix in prefixes:
        n = len(prefix)
        for key, value in msgs.items():
            if key.startswith(prefix):
                out[key[n:] or key] = value
    return json.dumps(out, ensure_ascii=False)
